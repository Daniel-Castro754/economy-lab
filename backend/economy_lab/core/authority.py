"""Canonical authority registry for Economy Lab engine composition.

v2.8 freezes an explicit answer to a question that previously lived mostly in
comments/documentation: *which engine is allowed to own each critical value?*

The registry separates realized state from advisory signals. External engines
never receive permission to mutate ledger balances or realized macro outcomes.
An :class:`AuthoritySession` records the active ownership plan and rejects
unauthorized or duplicate claims before they can be treated as canonical.
"""

from __future__ import annotations

from dataclasses import dataclass, field
from typing import Any, Iterable, Literal

from economy_lab.core.schemas import ScenarioSpec
from economy_lab.core.state import EconomyState


AUTHORITY_REGISTRY_VERSION = "1.0"
Cadence = Literal["run", "tick"]


class AuthorityError(RuntimeError):
    """Base error for authority-contract violations."""


class UnknownAuthorityFieldError(AuthorityError):
    pass


class UnauthorizedWriteError(AuthorityError):
    pass


class AuthorityConflictError(AuthorityError):
    pass


class MissingAuthorityClaimError(AuthorityError):
    pass


@dataclass(frozen=True, slots=True)
class VariableAuthorityContract:
    field: str
    allowed_sources: tuple[str, ...]
    cadence: Cadence
    description: str
    category: str


@dataclass(frozen=True, slots=True)
class AuthorityAssignment:
    field: str
    source: str
    cadence: Cadence
    description: str
    category: str


@dataclass(frozen=True, slots=True)
class AuthorityClaim:
    field: str
    source: str
    tick: int | None
    value: Any = None


@dataclass(slots=True)
class AuthorityAudit:
    registry_version: str
    strict: bool
    assignments: list[AuthorityAssignment]
    claims_by_source: dict[str, int]
    claims_by_field: dict[str, int]
    total_claims: int
    violations: list[str]
    complete: bool

    @property
    def status(self) -> str:
        return "pass" if self.complete and not self.violations else "fail"

    def to_dict(self) -> dict[str, object]:
        return {
            "registry_version": self.registry_version,
            "strict": self.strict,
            "status": self.status,
            "complete": self.complete,
            "total_claims": self.total_claims,
            "claims_by_source": dict(sorted(self.claims_by_source.items())),
            "claims_by_field": dict(sorted(self.claims_by_field.items())),
            "violations": list(self.violations),
            "assignments": [
                {
                    "field": item.field,
                    "source": item.source,
                    "cadence": item.cadence,
                    "description": item.description,
                    "category": item.category,
                }
                for item in self.assignments
            ],
        }


